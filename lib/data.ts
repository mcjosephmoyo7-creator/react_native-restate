function getRandomSubset<T>(array: T[], minItems: number, maxItems: number): T[] {
  const subsetSize =
    Math.floor(Math.random() * (maxItems - minItems + 1)) + minItems;
  const copy = [...array];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, subsetSize);
}

const agents: Agent[] = agentImages.map((avatar, index) => ({
  $id: `agent_${index + 1}`,
  name: `Agent ${index + 1}`,
  email: `agent${index + 1}@example.com`,
  avatar,
}));

const reviews: Review[] = reviewImages.map((avatar, index) => ({
  $id: `review_${index + 1}`,
  name: `Reviewer ${index + 1}`,
  avatar,
  review: `This is a review by Reviewer ${index + 1}. The property is fantastic and worth every penny.`,
  rating: Math.floor(Math.random() * 5) + 1,
  $createdAt: new Date(
    Date.now() - (index + 1) * 86400000
  ).toISOString(),
}));

const galleries: Gallery[] = galleryImages.map((image, index) => ({
  $id: `gallery_${index + 1}`,
  image,
}));

export const properties: Property[] = propertiesImages.map((image, index) => {
  const i = index + 1;
  const assignedAgent = agents[Math.floor(Math.random() * agents.length)];
  const assignedReviews = getRandomSubset(reviews, 3, 6);
  const assignedGalleries = getRandomSubset(galleries, 3, 8);

  return {
    $id: `property_${i}`,
    name: `Property ${i}`,
    type: propertyTypes[Math.floor(Math.random() * propertyTypes.length)],
    description: `This is the description for Property ${i}. A beautiful home located in a great neighborhood with modern amenities and easy access to everything.`,
    address: `123 Property Street, City ${i}`,
    geolocation: `192.168.1.${i}, 192.168.1.${i}`,
    price: Math.floor(Math.random() * 9000) + 1000,
    area: Math.floor(Math.random() * 3000) + 500,
    bedrooms: Math.floor(Math.random() * 5) + 1,
    bathrooms: Math.floor(Math.random() * 5) + 1,
    rating: Math.round((Math.floor(Math.random() * 40) + 10) / 10) / 1,
    facilities: getRandomSubset(facilities, 2, 6),
    image,
    agent: assignedAgent,
    reviews: assignedReviews,
    gallery: assignedGalleries,
    $createdAt: new Date(Date.now() - i * 43200000).toISOString(),
    $updatedAt: new Date(Date.now() - i * 43200000).toISOString(),
  };
});

export const getPropertyById = (id: string): Property | null =>
  properties.find((property) => property.$id === id) ?? null;